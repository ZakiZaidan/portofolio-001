// ── Pixel background generator ────────────────────────────────
function buildPixelColumns() {
  const NUM_COLS = 70
  const PAGE_HEIGHT_VH = 420
  const cols = []

  for (let c = 0; c < NUM_COLS; c++) {
    const base = (c / (NUM_COLS - 1)) * 100
    const jitter = ((c * 17 + 3) % 5) - 2.5
    const x = Math.max(0.3, Math.min(99.7, base + jitter))
    const baseOpacity = 0.12 + ((c * 7) % 8) * 0.025

    const pixels = []
    let y = ((c * 11) % 6) * 0.5

    while (y <= PAGE_HEIGHT_VH) {
      const hash = (c * 31 + pixels.length * 17) % 100
      if (hash > 12) {
        const opacity = baseOpacity + ((hash * 3) % 25) * 0.004
        pixels.push({ y, opacity })
      }
      const gapHash = (c * 41 + pixels.length * 23) % 100
      const step = gapHash < 8  ? 2.5 + (gapHash % 3)
                 : gapHash < 25 ? 1.0 + (gapHash % 10) * 0.06
                 :                0.5 + (gapHash % 10) * 0.04
      y += step
    }

    cols.push({ x, pixels, delay: ((c * 7) % 40) * 0.08 })
  }
  return cols
}

