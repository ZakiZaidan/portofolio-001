// ── Single alternating section ────────────────────────────────
function AboutSection({ image, imageBottom, imageTop, title, body, reverse, index }) {
  const ref = useRef(null)
  const isInView = useInView(ref, { once: true, margin: '-40px' })
  const isMobile = useIsMobile()

  // Di mobile: animasi fade-only (tanpa x-offset) agar gambar tidak geser keluar layar
  const imgVariant = {
    hidden:  { opacity: 0, x: isMobile ? 0 : (reverse ? 60 : -60) },
    visible: { opacity: 1, x: 0, transition: { duration: 0.7, ease: [0.22, 1, 0.36, 1] } },
  }
  const txtVariant = {
    hidden:  { opacity: 0, x: isMobile ? 0 : (reverse ? -60 : 60) },
    visible: { opacity: 1, x: 0, transition: { duration: 0.7, ease: [0.22, 1, 0.36, 1], delay: 0.1 } },
  }
  const lineVariant = {
    hidden:  { scaleX: 0 },
    visible: { scaleX: 1, transition: { duration: 0.6, ease: 'easeOut', delay: 0.3 } },
  }

  const isStacked = Boolean(imageBottom && imageTop)

  return (
    <div
      ref={ref}
      className={`about-section ${reverse ? 'about-section--reverse' : ''}`}
    >
      {/* Gambar — normal atau stacked */}
      <motion.div
        className="about-section-img"
        variants={imgVariant}
        initial="hidden"
        animate={isInView ? 'visible' : 'hidden'}
      >
        {isStacked
          ? <StackedImage bottom={imageBottom} top={imageTop} isInView={isInView} alt={title} />
          : <img src={image} alt={title} loading="lazy" />
        }
        <div className="about-img-overlay" />
        <span className="about-section-num">0{index + 1}</span>
      </motion.div>

      {/* Teks */}
      <motion.div
        className="about-section-text"
        variants={txtVariant}
        initial="hidden"
        animate={isInView ? 'visible' : 'hidden'}
      >
        <motion.div
          className="about-section-line"
          variants={lineVariant}
          initial="hidden"
          animate={isInView ? 'visible' : 'hidden'}
        />
        <h2 className="about-section-title">{title}</h2>
        <p className="about-section-body">{body}</p>
      </motion.div>
    </div>
  )
}

// ── Stacked image: down (bawah) + up (atas, reveal saat scroll) ──
function StackedImage({ bottom, top, isInView, alt }) {
  return (
    <div className="stacked-img">
      {/* Layer bawah — selalu terlihat */}
      <img
        src={bottom}
        alt={alt}
        className="stacked-img__bottom"
        loading="lazy"
      />

      {/* Layer atas — wipe UP dari bawah saat masuk viewport */}
      <motion.div
        className="stacked-img__top-wrapper"
        initial={{ clipPath: 'inset(100% 0 0 0)' }}
        animate={isInView
          ? { clipPath: 'inset(0% 0 0 0)' }
          : { clipPath: 'inset(100% 0 0 0)' }
        }
        transition={{ duration: 1.2, ease: [0.76, 0, 0.24, 1], delay: 0.35 }}
      >
        <img
          src={top}
          alt={alt}
          className="stacked-img__top"
          loading="lazy"
        />
      </motion.div>
    </div>
  )
}


